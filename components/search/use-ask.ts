"use client";

import { useCallback, useEffect, useRef, useState } from "react";
import type { AskSource } from "@/lib/ask/documents";
import { localAnswer } from "@/lib/ask/fallback";
import { type AskEvent, type AskUnavailable, readEvents } from "@/lib/ask/protocol";
import type { SearchPayload } from "@/lib/search/types";

/**
 * Asking, from Search (DESIGN.md §6.3, Part 14): posts the question to /api/ask and builds
 * the answer from the events as they stream. When the model can't answer (no key, a spent
 * limit, no connection) it answers from the site's own text instead, and says why.
 */

export interface AskBlock {
  text: string;
  /** Indexes into the answer's sources: the documents this block was drawn from. */
  sources: number[];
}

export type AskNotice = AskUnavailable | "nothing" | "declined";

export interface AskAnswer {
  /** asking: sent; streaming: the model is answering; done: whole. */
  phase: "idle" | "asking" | "streaming" | "done";
  question: string;
  /** generated by the model, or quoted from the site's own text. */
  mode: "generated" | "fallback";
  blocks: AskBlock[];
  sources: AskSource[];
  notice: AskNotice | null;
}

const IDLE: AskAnswer = { phase: "idle", question: "", mode: "generated", blocks: [], sources: [], notice: null };

export function useAsk(payload: SearchPayload | null) {
  const [answer, setAnswer] = useState<AskAnswer>(IDLE);
  const controller = useRef<AbortController | null>(null);

  const reset = useCallback(() => {
    controller.current?.abort();
    controller.current = null;
    setAnswer(IDLE);
  }, []);

  useEffect(() => () => controller.current?.abort(), []);

  const ask = useCallback(
    async (question: string) => {
      controller.current?.abort();
      const own = new AbortController();
      controller.current = own;
      const live = () => controller.current === own;

      /** The site's own text instead, with the reason. */
      const fallback = (reason: AskUnavailable) => {
        if (!live()) return;
        const snippets = payload ? localAnswer(question, payload.entries, payload.askSources, payload.profile) : [];
        const sources: AskSource[] = [];
        const blocks = snippets.map((snippet) => {
          if (!snippet.source) return { text: snippet.text, sources: [] };
          let index = sources.findIndex((source) => source.label === snippet.source!.label);
          if (index === -1) index = sources.push(snippet.source) - 1;
          return { text: snippet.text, sources: [index] };
        });
        setAnswer({ phase: "done", question, mode: "fallback", blocks, sources, notice: blocks.length > 0 ? reason : "nothing" });
      };

      setAnswer({ ...IDLE, phase: "asking", question });
      let response: Response;
      try {
        response = await fetch("/api/ask", {
          method: "POST",
          headers: { "Content-Type": "application/json" },
          body: JSON.stringify({ question }),
          signal: own.signal,
        });
      } catch {
        if (!own.signal.aborted) fallback(navigator.onLine === false ? "offline" : "unavailable");
        return;
      }
      if (!response.ok || !response.body || !(response.headers.get("content-type") ?? "").startsWith("text/event-stream")) {
        const reason = ((await response.json().catch(() => null)) as { reason?: AskUnavailable } | null)?.reason;
        fallback(reason === "rate" ? "rate" : "unavailable");
        return;
      }

      // The answer as it streams: blocks by the index the stream gives them.
      const blocks = new Map<number, AskBlock>();
      const sources: AskSource[] = [];
      const show = (phase: AskAnswer["phase"]) => {
        if (live()) setAnswer({ phase, question, mode: "generated", blocks: [...blocks.values()].map((block) => ({ ...block })), sources: [...sources], notice: null });
      };
      const block = (index: number) => {
        let found = blocks.get(index);
        if (!found) blocks.set(index, (found = { text: "", sources: [] }));
        return found;
      };
      let ended = false;
      try {
        for await (const event of readEvents(response.body) as AsyncGenerator<AskEvent>) {
          if (!live()) return;
          if (event.type === "start") show("streaming");
          else if (event.type === "text") {
            block(event.block).text += event.text;
            show("streaming");
          } else if (event.type === "source") {
            sources[event.index] = { label: event.label, target: event.target, href: event.href };
          } else if (event.type === "cite") {
            const cited = block(event.block);
            if (!cited.sources.includes(event.source)) cited.sources.push(event.source);
            show("streaming");
          } else if (event.type === "done") {
            ended = true;
            show("done");
          } else if (event.type === "declined") {
            // The stop reason says the answer doesn't stand: what streamed is dropped.
            ended = true;
            setAnswer({ phase: "done", question, mode: "generated", blocks: [], sources: [], notice: "declined" });
          } else if (event.type === "unavailable") {
            ended = true;
            fallback(event.reason);
          }
        }
      } catch {
        if (own.signal.aborted) return;
      }
      if (!ended) fallback(navigator.onLine === false ? "offline" : "unavailable");
    },
    [payload],
  );

  return { answer, ask, reset };
}
